/** The four care plan statuses returned by GET /orders */
export type OrderStatus = 'pending' | 'processing' | 'completed' | 'failed'

export type ResultType = 'SUCCESS' | 'WARNING'

/** Response body for POST /orders (201) and GET /orders/{id} (200) */
/** One duplicate-detection warning returned by the backend. */
export interface Warning {
    code: string
    message: string
    actionRequired: boolean
}

/** Shape of the JSON body the backend's ApiErrorResponse serializes to. */
export interface ApiErrorBody {
    type?: 'block' | 'warning' | 'validation' | 'error'
    code?: string
    message?: string
    detail?: unknown
    httpStatus?: number
}

/** The Error shape thrown by the axios interceptor in services/api.ts. */
export type ApiError = Error & {
    type?: ApiErrorBody['type']
    code?: string
    detail?: unknown
    status?: number   // the real HTTP status code, read from the transport layer
}

/** detail payload on a CONFIRMATION_REQUIRED (type: "warning") error */
export interface ConfirmationRequiredDetail {
    requiresConfirm: true
    warnings: Warning[]
}

/** Request body for POST /orders. Field names/types match the backend's
 *  CreateOrderRequest exactly -- no snake_case<->camelCase conversion layer. */
export interface CreateOrderRequest {
    patientFirstName: string
    patientLastName: string
    patientMrn: string
    patientDateOfBirth?: string          // "YYYY-MM-DD", optional
    patientSex?: string
    patientWeightKg?: number
    patientAllergies?: string
    providerName: string
    providerNpi: string
    medicationName: string
    primaryDiagnosis: string
    additionalDiagnoses: string[]
    medicationHistory: string[]
    patientRecords?: string
    confirm?: boolean
}

export interface OrderResponse {
    id: number
    patientId: number
    providerId: number
    patientFirstName: string
    patientLastName: string
    patientMrn: string
    patientDateOfBirth?: string
    providerName: string
    providerNpi: string
    medicationName: string
    status: OrderStatus
    carePlanContent?: string | null   // Present only when status === 'completed'
    resultType: ResultType
    message?: string | null
    warnings: Warning[]               // Structured objects since Phase 3
    requiresConfirm: boolean
}

/** A single item in the paginated GET /orders list; contains fewer fields than OrderResponse */
export interface OrderListItem {
    id: number
    patientName: string
    patientMrn: string
    medicationName: string
    status: OrderStatus
    createdAt: string                 // ISO-8601 UTC, e.g. "2026-08-30T12:34:56Z"
    providerName: string
    providerNpi: string
}

/** Paginated response for GET /orders: page-based pagination (page + pageSize), not next/previous URLs */
export interface PagedResponse<T> {
    count: number                     // Total number of records matching the filters, not the current page size
    page: number
    pageSize: number
    results: T[]
}

/** Polling response for GET /orders/{id}/status */
export interface CarePlanStatus {
    orderId: number
    status: OrderStatus
    carePlanPreview?: string
    errorMessage?: string
}

/**
 * Query parameters for GET /orders; these query param names remain snake_case on the backend.
 * All are optional and the backend ANDs the ones that are given. A parameter that is not wanted must be left
 * out, not sent as an empty string.
 */
export interface OrderListParams {
    page?: number                     // from 1
    page_size?: number                // 1..100
    status?: OrderStatus
    patient_id?: number
    provider_id?: number
    patient_name?: string             // part of the first name, last name or "first last", any case
    mrn?: string                      // exact match, 6 digits
    medication?: string               // part of the medication name, any case
    provider_name?: string            // part of the provider's name, any case
    created_from?: string             // yyyy-MM-dd, a UTC calendar day, included
    created_to?: string               // yyyy-MM-dd, a UTC calendar day, included; not before created_from
    /**
     * "field,direction", for example "created_at,desc". ONE string on purpose: axios would write an array as
     * sort[]=a&sort[]=b, which the backend does not read. Fields: id, created_at, medication, patient_name,
     * provider_name, status. Without it the newest orders come first.
     */
    sort?: string
}

// ---- GET /dashboard/stats (pharmacist only) ----------------------------------------------
// "No data" is null, never 0: failureRate and avgGenerationSeconds are null when nothing qualifies.

/** The two ranges the backend accepts; anything else is a 400 INVALID_DAYS. */
export type DashboardDays = 7 | 30

export interface DashboardKpi {
    totalOrders: number
    completedCount: number            // COMPLETED care plans generated by the LLM (manual uploads excluded)
    failedCount: number
    failureRate: number | null        // failed / (completed + failed), 0..1; null when none has finished
    avgGenerationSeconds: number | null
    manualUploadCount: number
}

export interface DashboardDailyOrders {
    date: string                      // "YYYY-MM-DD", a UTC calendar day
    count: number
}

/** Same definitions as the KPI, per order creation day; a day with nothing to measure has null rate/average. */
export interface DashboardDailyTrend {
    date: string
    completedCount: number
    failedCount: number
    failureRate: number | null
    avgGenerationSeconds: number | null
}

export interface DashboardStatusShare {
    status: OrderStatus               // lower-cased by dashboardService, like every other status
    count: number
    share: number                     // share of all orders in the window, 0..1
}

export interface DashboardMedicationCount {
    medicationName: string
    orderCount: number
}

export interface DashboardProviderStats {
    providerId: number
    providerName: string
    orderCount: number
    failedCount: number
    avgGenerationSeconds: number | null
}

export interface DashboardStats {
    days: DashboardDays
    from: string
    to: string
    timezone: string
    kpi: DashboardKpi
    dailyOrders: DashboardDailyOrders[]
    dailyTrend: DashboardDailyTrend[]
    statusBreakdown: DashboardStatusShare[]
    topMedications: DashboardMedicationCount[]
    providerStats: DashboardProviderStats[]
}
