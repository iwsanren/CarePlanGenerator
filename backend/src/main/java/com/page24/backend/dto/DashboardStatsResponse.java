package com.page24.backend.dto;

import io.swagger.v3.oas.annotations.media.Schema;

import java.time.LocalDate;
import java.util.List;

/**
 * Response of GET /api/v1/dashboard/stats. Every figure describes the orders created inside the window
 * [from, to] (inclusive, whole UTC calendar days).
 *
 * "No data" is null, never 0: failureRate and avgGenerationSeconds are null when no care plan qualifies. Care plans
 * that existed before the generation timing columns (all NULL), manual uploads, and plans still waiting or running
 * never contribute a duration.
 */
@Schema(description = "Dashboard figures for the orders created in the last N whole UTC days")
public record DashboardStatsResponse(
        @Schema(description = "Length of the window in days (7 or 30)") int days,
        @Schema(description = "First day of the window, UTC", example = "2026-11-08") LocalDate from,
        @Schema(description = "Last day of the window = today, UTC", example = "2026-11-14") LocalDate to,
        @Schema(description = "Time zone of the day boundaries", example = "UTC") String timezone,
        Kpi kpi,
        @Schema(description = "One entry for every day of the window; days without orders have count 0")
        List<DailyOrders> dailyOrders,
        @Schema(description = "One entry for every day of the window, in date order. Same definitions as kpi, "
                + "per day the order was created; a day with nothing to measure has null rate/average")
        List<DailyTrend> dailyTrend,
        @Schema(description = "All four statuses, always present, count 0 when there is none")
        List<StatusShare> statusBreakdown,
        @Schema(description = "Top medications by order count (case-insensitive name), at most 10")
        List<MedicationCount> topMedications,
        @Schema(description = "Top providers by order count, at most 10")
        List<ProviderStats> providerStats) {

    @Schema(description = "Headline figures. Failure rate and duration only look at LLM-generated care plans "
            + "(manual uploads are excluded) and only at plans that have finished.")
    public record Kpi(
            @Schema(description = "Orders created in the window") long totalOrders,
            @Schema(description = "COMPLETED care plans generated by the LLM") long completedCount,
            @Schema(description = "FAILED care plans") long failedCount,
            @Schema(description = "failedCount / (completedCount + failedCount), 0 to 1, 4 decimals; "
                    + "null when both are 0", nullable = true) Double failureRate,
            @Schema(description = "Average finished_at - started_at in seconds over COMPLETED LLM care plans "
                    + "that have both timestamps (includes the retry back-off), 2 decimals; null when there is "
                    + "no such plan", nullable = true) Double avgGenerationSeconds,
            @Schema(description = "Care plans that were uploaded manually; excluded from failure rate and duration")
            long manualUploadCount) {
    }

    public record DailyOrders(
            @Schema(example = "2026-11-08") LocalDate date,
            long count) {
    }

    public record DailyTrend(
            @Schema(example = "2026-11-08") LocalDate date,
            @Schema(description = "COMPLETED care plans generated by the LLM, for orders created that day")
            long completedCount,
            @Schema(description = "FAILED care plans, for orders created that day") long failedCount,
            @Schema(description = "failedCount / (completedCount + failedCount), 0 to 1, 4 decimals; "
                    + "null when both are 0", nullable = true) Double failureRate,
            @Schema(description = "Average finished_at - started_at in seconds, same rules as kpi, 2 decimals; "
                    + "null when no plan of that day qualifies", nullable = true) Double avgGenerationSeconds) {
    }

    public record StatusShare(
            @Schema(allowableValues = {"PENDING", "PROCESSING", "COMPLETED", "FAILED"}) String status,
            long count,
            @Schema(description = "count / total care plans, 0 to 1, 4 decimals; 0 when there are none")
            double share) {
    }

    public record MedicationCount(String medicationName, long orderCount) {
    }

    public record ProviderStats(
            long providerId,
            String providerName,
            long orderCount,
            @Schema(description = "FAILED care plans among these orders") long failedCount,
            @Schema(description = "Same definition as in kpi; null when no care plan qualifies", nullable = true)
            Double avgGenerationSeconds) {
    }
}
